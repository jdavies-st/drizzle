"""
Pixel-level regression tests that pin the outputs of every drizzle kernel
and every blot interpolator.

The reference arrays in ``data/reference_outputs.fits`` were produced by this
module, one image extension per case, named after the case (for example
``DRIZZLE_SQUARE_IMG`` or ``BLOT_POLY5``). After an intended change in
results, regenerate them with::

    python -m drizzle.tests.test_reference_outputs

Inputs and pixel maps are built from exact integer and rational arithmetic
so that they are bit-identical on every platform. The comparison tolerance
allows for differences in floating point contraction and summation order
between compilers, but is tight enough to catch changes in the algorithms.
"""

import os
import warnings

import numpy as np
import pytest

from astropy.io import fits
from drizzle import resample
from drizzle.tests.helpers import DATA_DIR

REFERENCE_FILE = os.path.join(DATA_DIR, "reference_outputs.fits")

DRIZZLE_KERNELS = resample.SUPPORTED_DRIZZLE_KERNELS
BLOT_INTERPOLATORS = ["nearest", "linear", "poly3", "poly5", "lanczos3", "lanczos5"]

IN_SHAPE = (48, 48)
OUT_SHAPE = (56, 56)

# rotation with exact rational cosine and sine (7-24-25 triangle)
COS_T = 24.0 / 25.0
SIN_T = 7.0 / 25.0

RTOL = 1.0e-5

# Lanczos weights can be negative, so the accumulated weight can come close to
# zero and the weighted mean there is dominated by rounding. For these kernels
# the output images are compared only where the weight is not small.
MIN_ABS_WEIGHT = {"lanczos2": 0.05, "lanczos3": 0.05}


def _make_data(shape):
    y, x = np.indices(shape)
    pattern = ((x * x * 7919 + y * y * 104729 + x * y * 31) % 997) / 997.0
    data = 10.0 * pattern + 0.5 * x + 0.25 * y
    data[12, 20] += 500.0
    data[30, 9] += 300.0
    return data.astype(np.float32)


def _make_weights(shape):
    y, x = np.indices(shape)
    weights = 0.5 + ((x * 31 + y * 17) % 11) / 10.0
    weights[:, 25] = 0.0
    return weights.astype(np.float32)


def _make_pixmap(shape, center_in, center_out, scale, quad, shift=(0.0, 0.0)):
    """Rotated and scaled grid with a small quadratic distortion."""
    y, x = np.indices(shape, dtype=np.float64)
    xc = x - center_in[0]
    yc = y - center_in[1]
    xo = center_out[0] + shift[0] + scale * (COS_T * xc - SIN_T * yc) + quad * xc * xc
    yo = center_out[1] + shift[1] + scale * (SIN_T * xc + COS_T * yc) + quad * xc * yc
    return np.dstack([xo, yo])


def _drizzle(kernel):
    data = _make_data(IN_SHAPE)
    weights = _make_weights(IN_SHAPE)
    variance = 0.1 * data + 1.0
    # lanczos kernels ignore pixfrac and warn when it is not 1
    pixfrac = 1.0 if kernel.startswith("lanczos") else 0.8
    driz = resample.Drizzle(kernel=kernel, out_shape=OUT_SHAPE, fillval="NaN", fillval2="NaN")

    pixmap = _make_pixmap(IN_SHAPE, (23.5, 23.5), (27.5, 27.3), 1.05, 1.0e-3)
    driz.add_image(
        data,
        exptime=1.0,
        pixmap=pixmap,
        data2=variance,
        weight_map=weights,
        pixel_scale_ratio=1.05,
        pixfrac=pixfrac,
    )

    pixmap = _make_pixmap(IN_SHAPE, (23.5, 23.5), (27.5, 27.3), 1.05, 1.0e-3, (0.375, -0.625))
    driz.add_image(
        2.0 * data,
        exptime=2.0,
        pixmap=pixmap,
        data2=2.0 * variance,
        weight_map=weights,
        wht_scale=0.5,
        pixel_scale_ratio=1.05,
        pixfrac=pixfrac,
        in_units="counts",
    )

    return {"img": driz.out_img, "wht": driz.out_wht, "img2": driz.out_img2[0]}


def _blot(interp):
    data = _make_data(IN_SHAPE)
    pixmap = _make_pixmap(OUT_SHAPE, (27.5, 27.5), (23.5, 23.3), 0.9, 1.0e-3)
    return resample.blot_image(data, pixmap=pixmap, iscale=1.1, fillval=np.nan, interp=interp)


def _compute_all():
    results = {}
    for kernel in DRIZZLE_KERNELS:
        for name, arr in _drizzle(kernel).items():
            results[f"drizzle_{kernel}_{name}"] = arr
    for interp in BLOT_INTERPOLATORS:
        results[f"blot_{interp}"] = _blot(interp)
    return results


def _write_reference(filename):
    primary = fits.PrimaryHDU()
    primary.header["COMMENT"] = "Generated by python -m drizzle.tests.test_reference_outputs"
    hdus = [fits.ImageHDU(arr, name=name.upper()) for name, arr in _compute_all().items()]
    fits.HDUList([primary, *hdus]).writeto(filename, overwrite=True)


def _assert_matches_reference(actual, desired, mask=None):
    np.testing.assert_array_equal(np.isnan(actual), np.isnan(desired))
    if mask is not None:
        actual = actual[mask]
        desired = desired[mask]
    atol = RTOL * np.nanmax(np.abs(desired))
    np.testing.assert_allclose(actual, desired, rtol=RTOL, atol=atol, equal_nan=True)


@pytest.fixture(scope="module")
def reference():
    with fits.open(REFERENCE_FILE) as hdul:
        # FITS data are big-endian; convert to native float32 copies
        return {hdu.name.lower(): hdu.data.astype(np.float32) for hdu in hdul[1:]}


@pytest.mark.filterwarnings("ignore:Kernel '.*' is not a flux-conserving kernel:Warning")
@pytest.mark.parametrize("kernel", DRIZZLE_KERNELS)
def test_drizzle_reference(reference, kernel):
    result = _drizzle(kernel)
    _assert_matches_reference(result["wht"], reference[f"drizzle_{kernel}_wht"])

    mask = None
    if kernel in MIN_ABS_WEIGHT:
        mask = np.abs(reference[f"drizzle_{kernel}_wht"]) >= MIN_ABS_WEIGHT[kernel]
    for name in ["img", "img2"]:
        _assert_matches_reference(result[name], reference[f"drizzle_{kernel}_{name}"], mask)


@pytest.mark.parametrize("interp", BLOT_INTERPOLATORS)
def test_blot_reference(reference, interp):
    _assert_matches_reference(_blot(interp), reference[f"blot_{interp}"])


if __name__ == "__main__":
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        _write_reference(REFERENCE_FILE)
    print(f"Wrote {REFERENCE_FILE}")
